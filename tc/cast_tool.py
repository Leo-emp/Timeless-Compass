# CAST LIBRARY TOOL: how a video gets all its people.
#   level 1 MAIN characters (named historical figures): designed once from sources -> library/cast/<name>.json
#   level 2 SUPPORTING characters: a generated person (tc/crowd.py) PROMOTED to a named, saved character, so he
#           looks the same in every shot (and can return in later videos)
#   level 3 EXTRAS: generated per video by tc/crowd.py, never saved
#   python -m tc cast list                                       every library character
#   python -m tc cast missing <job>                              named people a job needs that don't exist yet
#   python -m tc cast promote <name> --role commander --era greece_480bc --seed 77 --who "trierarch at Salamis"
#   then render its character card:  blender -b --python blender/scenes/cast_card.py -- <name>
import json
from pathlib import Path

from tc import crowd, jobs
from tc.cli import register
from tc.paths import LIBRARY

CAST = LIBRARY / "cast"


def promote(name: str, role: str, era: str, seed: int, root: Path = CAST, who: str = "") -> dict:
    root = Path(root)
    dest = root / f"{name}.json"
    if dest.exists():
        raise FileExistsError(f"{name} already exists in the cast library")
    p = crowd.person(seed, role, era)
    spec = {"name": name, "version": 1, "era": era, "role": role, "who": who or f"{role} ({era})",
            "design_source": "generated (tc crowd) and promoted to a named character",
            "generated_from": {"role": role, "era": era, "seed": seed},
            "licence": "MakeHuman/MPFB assets CC0; strand hair generated by our code", "owner_rating": None, "used_in": []}
    for k in ("macro", "skin", "face", "tan", "age_lines", "stubble", "hair", "beard", "wardrobe", "dye", "shield", "helmet"):
        if k in p:
            spec[k] = p[k]
    root.mkdir(parents=True, exist_ok=True)
    text = json.dumps(spec, indent=2, ensure_ascii=False)
    dest.write_text(text, encoding="utf-8")
    return json.loads(text)                                   # exactly what is on disk (tuples become lists)


def missing(needs: dict, root: Path = CAST) -> list[str]:
    """Named people in a job's needs.json without a library file (crowd:<role>:<n> entries are generated, so skip)."""
    root = Path(root)
    return [w for w in needs.get("who", []) if not w.startswith("crowd:") and not (root / f"{w}.json").exists()]


def _args(p):
    p.add_argument("action", choices=["list", "missing", "promote"])
    p.add_argument("target", nargs="?", help="job id (missing) or character name (promote)")
    p.add_argument("--role"); p.add_argument("--era", default="greece_480bc")
    p.add_argument("--seed", type=int, default=0); p.add_argument("--who", default="")


@register("cast", "character library: list, find missing named people, promote a generated extra", _args)
def _cmd_cast(args) -> int:
    if args.action == "list":
        for f in sorted(CAST.glob("*.json")):
            m = json.loads(f.read_text(encoding="utf-8"))
            print(f"{f.stem:14s} {m.get('era', ''):14s} rating {m.get('owner_rating')}  {m.get('who', '')[:70]}")
        return 0
    if args.action == "missing":
        needs = json.loads((jobs.job_dir(args.target) / "needs.json").read_text(encoding="utf-8"))
        gone = missing(needs)
        for g in gone:
            print("-", g)
        print(f"{len(gone)} named characters to design")
        return 1 if gone else 0
    if not (args.target and args.role):
        print("promote needs a name and --role"); return 2
    spec = promote(args.target, args.role, args.era, args.seed, who=args.who)
    print("saved", spec["name"], "->", CAST / f"{spec['name']}.json")
    return 0
