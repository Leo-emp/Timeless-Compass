# WIRING A JOB INTO THE FILM (plan 4): the job's fresh scene code + timed plan become a Remotion composition, the
# shot plan's word-anchored sounds/music become the mix's cue files, and the silent cloud render gets its audio.
#   film/src/jobs/<slug>/scenes.ts   fresh scene code for this video (exports SCENES)          (rule r17)
#   film/src/jobs/<slug>/plan.json   timed plan from `tc shotplan`
#   film/src/jobs/index.ts           generated list of every job -> compositions Job_<slug>
#   python -m tc filmjob build <job>          index + sound.json + music.json (for tc mix)
#   python -m tc filmjob mux <job> <video>    video + jobs/<id>/mix.wav -> jobs/<id>/master.mp4
import json
import re
import subprocess
from pathlib import Path

from tc import jobs
from tc.cli import register
from tc.paths import ROOT

FILM_JOBS = ROOT / "film" / "src" / "jobs"
BED_MAX_S = 4.0     # a long sound (waves, fire bed) placed on a word is trimmed to 4 s
CUE_MOODS = {"hook": ["dread", "tension", "mystery"], "tension": ["tension", "dread", "menace"],
             "battle": ["tension", "menace", "triumph"], "climax": ["triumph", "tension", "awe"],
             "emotional": ["grief", "hope"], "ending": ["awe", "hope", "grief", "mystery"]}


def slug(job_id: str) -> str:
    return re.sub(r"[^a-z0-9_]", "_", job_id.lower())


def write_index(jobs_dir: Path) -> str:
    """TypeScript source listing every job folder that has a plan.json + scenes.ts (Root.tsx registers them)."""
    entries = sorted(p.parent.name for p in Path(jobs_dir).glob("*/plan.json") if (p.parent / "scenes.ts").exists())
    lines = ["// GENERATED by `python -m tc filmjob build` - every job with a timed plan + fresh scenes.",
             "import type { SceneFn, TimedPlan } from '../film/sequence';"]
    for i, e in enumerate(entries):
        lines += [f"import plan{i} from './{e}/plan.json';", f"import {{ SCENES as scenes{i} }} from './{e}/scenes';"]
    lines.append("export const JOBS: { slug: string; plan: TimedPlan; scenes: Record<string, SceneFn> }[] = [")
    lines += [f"  {{ slug: '{e}', plan: plan{i} as unknown as TimedPlan, scenes: scenes{i} }}," for i, e in enumerate(entries)]
    lines.append("];\n")
    return "\n".join(lines)


def sound_from_plan(timed: dict, sfx_idx: dict) -> dict:
    """sound.json for tc mix: every sound effect exactly on its word (r28)."""
    dur = {s["id"]: float(s.get("duration", BED_MAX_S)) for s in sfx_idx.get("sounds", [])}
    events = []
    for s in timed["shots"]:
        for x in s.get("sfx", []):
            if x.get("at") is None:
                continue
            events.append({"sound": x["sound"], "at": x["at"], "dur": min(BED_MAX_S, dur.get(x["sound"], BED_MAX_S)),
                           "db": x.get("db", -12)})
    return {"events": events, "ambience": []}


def _pick(cue: str, tracks: dict, used: set) -> str | None:
    """Best unused track for a cue kind, by mood order (music by meaning, never the same track twice)."""
    moods, best = CUE_MOODS.get(cue, []), None
    for t in tracks.get("tracks", []):
        if t["id"] in used:
            continue
        rank = min((moods.index(m) for m in t.get("moods", []) if m in moods), default=None)
        if rank is not None and (best is None or rank < best[0]):
            best = (rank, t["id"])
    return best[1] if best else None


def music_from_plan(timed: dict, tracks: dict) -> dict:
    """music.json for tc mix: a cue ONLY on shots that name one (r11), lasting to the end of that shot."""
    fps, cues, used = timed.get("fps", 24), [], set()
    for s in timed["shots"]:
        m = s.get("music")
        if not m:
            continue
        wanted = m.get("track") or _pick(m["cue"], tracks, used)
        if not wanted:
            continue
        used.add(wanted)
        t = next(x for x in tracks["tracks"] if x["id"] == wanted)
        at = m.get("at")
        at = s["start_f"] / fps if at is None else at
        # a cue lasts to the end of its shot, or to the end of the shot named in "until" (one piece across a sequence)
        end_shot = next((x for x in timed["shots"] if x["id"] == m.get("until")), s)
        cues.append({"track": wanted, "file": t["file"], "at": at, "dur": round(end_shot["end_f"] / fps - at, 3),
                     "db": m.get("db", -16), "fade_in": 1.0, "fade_out": 2.5})
    return {"cues": cues}


def _probe(path: Path) -> float:
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)],
                         capture_output=True, text=True, check=True).stdout
    return float(out.strip())


def mux(video: Path, audio: Path, out: Path, probe=_probe, runner=subprocess.run) -> Path:
    """Silent cloud render + the mix -> master. Refuses if they differ by more than 0.1 s (it would drift out of sync)."""
    v, a = probe(video), probe(audio)
    if abs(v - a) > 0.1:
        raise ValueError(f"video length {v:.2f} s and audio length {a:.2f} s differ: re-render or re-mix first")
    runner(["ffmpeg", "-v", "error", "-y", "-i", str(video), "-i", str(audio), "-map", "0:v", "-map", "1:a",
            "-c:v", "copy", "-c:a", "aac", "-b:a", "256k", "-shortest", str(out)], check=True)
    return out


def _args(p):
    sub = p.add_subparsers(dest="action", required=True)
    a = sub.add_parser("build")
    a.add_argument("job")
    a = sub.add_parser("mux")
    a.add_argument("job")
    a.add_argument("video")


@register("filmjob", "film wiring: build (scene index + sound/music cues), mux (video + mix -> master)", _args)
def _cmd_filmjob(args) -> int:
    from tc import music as music_mod, sfx as sfx_mod
    d = jobs.job_dir(args.job)
    if args.action == "build":
        (FILM_JOBS / "index.ts").write_text(write_index(FILM_JOBS), encoding="utf-8")
        timed = json.loads((FILM_JOBS / slug(args.job) / "plan.json").read_text(encoding="utf-8"))
        (d / "sound.json").write_text(json.dumps(sound_from_plan(timed, sfx_mod.load_index()), indent=1), encoding="utf-8")
        (d / "music.json").write_text(json.dumps(music_from_plan(timed, music_mod.load_tracks()), indent=1), encoding="utf-8")
        print(f"index + cues written; composition: Job-{slug(args.job).replace("_", "-")}")
        return 0
    print(mux(Path(args.video), d / "mix.wav", d / "master.mp4"))
    return 0
